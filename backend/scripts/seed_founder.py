"""Seed the founder account, the plan records and the founder's
subscription + preferences (Phase 8.1; design 02 §1.4, §3.2, §5.1).

This is an operator script, NOT an Alembic migration: no credential
ever enters migration history. It is idempotent — re-running it
changes nothing unless --reset-password is passed.

Behaviour:
- Ensures the four plan records exist (founder/free/pro/studio).
  Existing plans are left untouched (they are operator-tunable).
- Creates the founder user (default email mirthdraught@gmail.com,
  override with CINEMORA_FOUNDER_EMAIL) with role super_admin on
  the founder plan, plus an empty preferences document.
- The founder's initial password is a strong random value generated
  here, Argon2id-hashed into the database, and written in plaintext
  ONLY to the password file (default
  ~/workspace/cinemora-preview/founder-initial-password.txt,
  override with --password-file / CINEMORA_FOUNDER_PASSWORD_FILE),
  created with mode 0600. It is never printed, never logged.
- --reset-password is the break-glass path (02 §1.4): it generates
  a fresh password, replaces the hash, rewrites the password file,
  and (Phase 8.2) revokes the founder's sessions.

Usage (from the backend directory):
    DATABASE_URL=sqlite:////path/to.db python scripts/seed_founder.py
    DATABASE_URL=... python scripts/seed_founder.py --reset-password
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from argon2 import PasswordHasher  # noqa: E402

from database import SessionLocal  # noqa: E402
import models  # noqa: E402

FOUNDER_EMAIL_DEFAULT = "mirthdraught@gmail.com"
PASSWORD_FILE_DEFAULT = (
    Path.home() / "workspace" / "cinemora-preview" / "founder-initial-password.txt"
)

# Effectively-unlimited sentinel for the founder plan's NOT NULL
# integer caps (02 §5.1: founder = unlimited everything). Enforcement
# compares live counts against the cap, so int32-max never binds.
UNLIMITED = 2_147_483_647

PLANS = [
    # name, concurrent, runs/month, script chars, storage B, upload B, tier, default
    ("founder", UNLIMITED, None, None, None, None, 1, False),
    ("free", 1, 3, 20_000, 2 * 1024**3, 512 * 1024**2, 0, True),
    ("pro", 2, 20, 60_000, 20 * 1024**3, 512 * 1024**2, 1, False),
    ("studio", 4, 60, 120_000, 100 * 1024**3, 1024**3, 1, False),
]


def _write_password_file(path: Path, email: str, password: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Write via a fresh fd with 0600 from the start — the file must
    # never exist with looser permissions.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        os.write(
            fd,
            (
                f"email: {email}\n"
                f"password: {password}\n"
                "Generated by scripts/seed_founder.py. Change after "
                "first login; delete this file once the password is "
                "stored in your password manager.\n"
            ).encode(),
        )
    finally:
        os.close(fd)
    os.chmod(path, 0o600)


def ensure_plans(db) -> dict[str, models.Plan]:
    plans: dict[str, models.Plan] = {}
    for (
        name,
        concurrent,
        per_period,
        script_chars,
        storage,
        upload,
        tier,
        is_default,
    ) in PLANS:
        plan = db.query(models.Plan).filter_by(name=name).one_or_none()
        if plan is None:
            plan = models.Plan(
                id=str(uuid.uuid4()),
                name=name,
                max_concurrent_runs=concurrent,
                max_runs_per_period=per_period,
                period="month",
                max_script_chars=script_chars,
                max_storage_bytes=storage,
                max_upload_bytes=upload,
                priority_tier=tier,
                is_default=is_default,
            )
            db.add(plan)
            db.flush()
        plans[name] = plan
    return plans


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reset-password", action="store_true")
    parser.add_argument("--password-file", type=Path, default=None)
    args = parser.parse_args()

    email = os.environ.get("CINEMORA_FOUNDER_EMAIL", FOUNDER_EMAIL_DEFAULT)
    email = email.strip().lower()
    password_file = (
        args.password_file
        or Path(
            os.environ.get(
                "CINEMORA_FOUNDER_PASSWORD_FILE", str(PASSWORD_FILE_DEFAULT)
            )
        )
    )

    hasher = PasswordHasher()
    db = SessionLocal()
    try:
        plans = ensure_plans(db)

        founder = (
            db.query(models.User).filter_by(email=email).one_or_none()
        )
        created = False
        password_changed = False
        if founder is None:
            password = secrets.token_urlsafe(36)
            founder = models.User(
                id=str(uuid.uuid4()),
                email=email,
                password_hash=hasher.hash(password),
                display_name="Founder",
                role="super_admin",
                status="active",
            )
            db.add(founder)
            db.flush()
            _write_password_file(password_file, email, password)
            created = True
            password_changed = True
        elif args.reset_password:
            password = secrets.token_urlsafe(36)
            founder.password_hash = hasher.hash(password)
            _write_password_file(password_file, email, password)
            password_changed = True
            # Session revocation lives in services/auth.py (8.2);
            # imported lazily so this script still runs pre-8.2.
            try:
                from services import auth as auth_service

                auth_service.revoke_all_sessions(founder.id)
            except ImportError:
                pass

        sub = (
            db.query(models.UserSubscription)
            .filter_by(user_id=founder.id, status="active")
            .one_or_none()
        )
        if sub is None:
            now = datetime.now(timezone.utc)
            db.add(
                models.UserSubscription(
                    id=str(uuid.uuid4()),
                    user_id=founder.id,
                    plan_id=plans["founder"].id,
                    status="active",
                    current_period_start=now,
                    current_period_end=None,
                )
            )

        prefs = (
            db.query(models.UserPreference)
            .filter_by(user_id=founder.id)
            .one_or_none()
        )
        if prefs is None:
            db.add(
                models.UserPreference(
                    user_id=founder.id,
                    document={"studio": {}, "assistant": {}, "notifications": {}},
                )
            )

        db.commit()
    finally:
        db.close()

    print(f"plans ensured: {', '.join(sorted(plans))}")
    print(f"founder: {email} ({'created' if created else 'already existed'})")
    if password_changed:
        print(f"initial password written to: {password_file} (mode 0600)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
