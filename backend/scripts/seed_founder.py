"""Seed the founder account, the plan records and the founder's
subscription + preferences (Phase 8.1; design 02 §1.4, §3.2, §5.1).

This is an operator script, NOT an Alembic migration: no credential
ever enters migration history. It is idempotent — re-running it
changes nothing unless --reset-password is passed.

Behaviour:
- Ensures the four plan records exist (founder/free/pro/studio).
  Existing plans are left untouched (they are operator-tunable).
- Creates the founder user (default email mirthdraught@gmail.com,
  override with CINEMORA_FOUNDER_EMAIL) with role super_admin on
  the founder plan, plus an empty preferences document.
- The founder's initial password is a strong random value generated
  here, Argon2id-hashed into the database, and written in plaintext
  ONLY to the password file (default
  ~/workspace/cinemora-preview/founder-initial-password.txt,
  override with --password-file / CINEMORA_FOUNDER_PASSWORD_FILE),
  created with mode 0600. It is never printed, never logged.
- --reset-password is the break-glass path (02 §1.4): it generates
  a fresh password, replaces the hash, rewrites the password file,
  and (Phase 8.2) revokes the founder's sessions.

Usage (from the backend directory):
    DATABASE_URL=sqlite:////path/to.db python scripts/seed_founder.py
    DATABASE_URL=... python scripts/seed_founder.py --reset-password
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from argon2 import PasswordHasher  # noqa: E402

from database import SessionLocal  # noqa: E402
import models  # noqa: E402

FOUNDER_EMAIL_DEFAULT = "mirthdraught@gmail.com"
PASSWORD_FILE_DEFAULT = (
    Path.home() / "workspace" / "cinemora-preview" / "founder-initial-password.txt"
)

# Effectively-unlimited sentinel for the founder plan's NOT NULL
# integer caps (02 §5.1: founder = unlimited everything). Enforcement
# compares live counts against the cap, so int32-max never binds.
UNLIMITED = 2_147_483_647

PLANS = [
    # name, concurrent, runs/month, script chars, storage B, upload B, tier, default
    ("founder", UNLIMITED, None, None, None, None, 1, False),
    ("free", 1, 3, 20_000, 2 * 1024**3, 512 * 1024**2, 0, True),
    ("pro", 2, 20, 60_000, 20 * 1024**3, 512 * 1024**2, 1, False),
    ("studio", 4, 60, 120_000, 100 * 1024**3, 1024**3, 1, False),
]


def _write_password_file(path: Path, email: str, password: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Write via a fresh fd with 0600 from the start — the file must
    # never exist with looser permissions.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        os.write(
            fd,
            (
                f"email: {email}\n"
                f"password: {password}\n"
                "Generated by scripts/seed_founder.py. Change after "
                "first login; delete this file once the password is "
                "stored in your password manager.\n"
            ).encode(),
        )
    finally:
        os.close(fd)
    os.chmod(path, 0o600)


def _billing_schema_ready(db) -> bool:
    """True when the database has the Phase 8 monetization schema
    (migration 0013+: commercial plan columns + topup_packages).

    This script is an operator step in the 0006 -> seed ->
    backfill -> 0007 upgrade path (see
    tests/test_phase8_data_layer.py), so it MUST run against a
    pre-0013 database: the current ORM models carry columns that
    do not exist there yet, and the billing catalogue sync can
    only run once 0013 has landed. On a legacy-schema database
    the seed therefore uses reflected Core tables (only the
    columns that actually exist) and skips the catalogue sync;
    re-running the seed after the upgrade to head performs it.
    """
    from sqlalchemy import inspect as sa_inspect

    inspector = sa_inspect(db.bind)
    if not inspector.has_table("topup_packages"):
        return False
    plan_columns = {c["name"] for c in inspector.get_columns("plans")}
    return "price_monthly_cents" in plan_columns


def ensure_plans(db, *, billing_ready: bool = True):
    """Ensure the four legacy plan rows exist.

    Returns a name -> plan mapping (ORM objects on a current
    schema; id-only namespaces on a pre-0013 schema, where the
    ORM would select/insert columns the database does not have).
    """
    plans = {}
    if not billing_ready:
        from types import SimpleNamespace

        from sqlalchemy import MetaData, Table

        plans_table = Table(
            "plans", MetaData(), autoload_with=db.bind
        )
        for (
            name,
            concurrent,
            per_period,
            script_chars,
            storage,
            upload,
            tier,
            is_default,
        ) in PLANS:
            row = db.execute(
                plans_table.select().where(plans_table.c.name == name)
            ).first()
            if row is None:
                plan_id = str(uuid.uuid4())
                db.execute(
                    plans_table.insert().values(
                        id=plan_id,
                        name=name,
                        max_concurrent_runs=concurrent,
                        max_runs_per_period=per_period,
                        period="month",
                        max_script_chars=script_chars,
                        max_storage_bytes=storage,
                        max_upload_bytes=upload,
                        priority_tier=tier,
                        is_default=is_default,
                    )
                )
                db.flush()
            else:
                plan_id = row.id
            plans[name] = SimpleNamespace(id=plan_id)
        return plans
    for (
        name,
        concurrent,
        per_period,
        script_chars,
        storage,
        upload,
        tier,
        is_default,
    ) in PLANS:
        plan = db.query(models.Plan).filter_by(name=name).one_or_none()
        if plan is None:
            plan = models.Plan(
                id=str(uuid.uuid4()),
                name=name,
                max_concurrent_runs=concurrent,
                max_runs_per_period=per_period,
                period="month",
                max_script_chars=script_chars,
                max_storage_bytes=storage,
                max_upload_bytes=upload,
                priority_tier=tier,
                is_default=is_default,
            )
            db.add(plan)
            db.flush()
        plans[name] = plan
    return plans


def _ensure_founder_subscription(db, founder_id: str, plan_id: str,
                                 *, billing_ready: bool) -> None:
    """Ensure the founder has an active subscription, on either
    schema generation (see _billing_schema_ready)."""
    if not billing_ready:
        from sqlalchemy import MetaData, Table

        subs_table = Table(
            "user_subscriptions", MetaData(), autoload_with=db.bind
        )
        row = db.execute(
            subs_table.select().where(
                subs_table.c.user_id == founder_id,
                subs_table.c.status == "active",
            )
        ).first()
        if row is None:
            db.execute(
                subs_table.insert().values(
                    id=str(uuid.uuid4()),
                    user_id=founder_id,
                    plan_id=plan_id,
                    status="active",
                    current_period_start=datetime.now(timezone.utc),
                    current_period_end=None,
                    created_at=datetime.now(timezone.utc),
                )
            )
            db.flush()
        return
    sub = (
        db.query(models.UserSubscription)
        .filter_by(user_id=founder_id, status="active")
        .one_or_none()
    )
    if sub is None:
        now = datetime.now(timezone.utc)
        db.add(
            models.UserSubscription(
                id=str(uuid.uuid4()),
                user_id=founder_id,
                plan_id=plan_id,
                status="active",
                current_period_start=now,
                current_period_end=None,
            )
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reset-password", action="store_true")
    parser.add_argument("--password-file", type=Path, default=None)
    args = parser.parse_args()

    email = os.environ.get("CINEMORA_FOUNDER_EMAIL", FOUNDER_EMAIL_DEFAULT)
    email = email.strip().lower()
    password_file = (
        args.password_file
        or Path(
            os.environ.get(
                "CINEMORA_FOUNDER_PASSWORD_FILE", str(PASSWORD_FILE_DEFAULT)
            )
        )
    )

    hasher = PasswordHasher()
    db = SessionLocal()
    try:
        billing_ready = _billing_schema_ready(db)
        plans = ensure_plans(db, billing_ready=billing_ready)

        # Phase 8: the founder-priced billing catalogue (metered
        # plans + top-up packages). Idempotent; updates commercial
        # fields only (services/billing/catalogue.py). Only on a
        # post-0013 schema — on the pre-0013 upgrade path the
        # catalogue tables/columns do not exist yet, and the sync
        # happens when the seed is re-run after the upgrade.
        if billing_ready:
            from services.billing import catalogue as billing_catalogue

            catalogue_report = billing_catalogue.ensure_billing_catalogue(db)
        else:
            catalogue_report = {
                "plans_created": [], "packages_created": [],
                "plans_updated": [], "packages_updated": [],
            }

        founder = (
            db.query(models.User).filter_by(email=email).one_or_none()
        )
        created = False
        password_changed = False
        if founder is None:
            password = secrets.token_urlsafe(36)
            founder = models.User(
                id=str(uuid.uuid4()),
                email=email,
                password_hash=hasher.hash(password),
                display_name="Founder",
                role="super_admin",
                status="active",
            )
            db.add(founder)
            db.flush()
            _write_password_file(password_file, email, password)
            created = True
            password_changed = True
        elif args.reset_password:
            password = secrets.token_urlsafe(36)
            founder.password_hash = hasher.hash(password)
            _write_password_file(password_file, email, password)
            password_changed = True
            # Session revocation lives in services/auth.py (8.2);
            # imported lazily so this script still runs pre-8.2.
            try:
                from services import auth as auth_service

                auth_service.revoke_all_sessions(founder.id)
            except ImportError:
                pass

        _ensure_founder_subscription(
            db, founder.id, plans["founder"].id,
            billing_ready=billing_ready,
        )

        prefs = (
            db.query(models.UserPreference)
            .filter_by(user_id=founder.id)
            .one_or_none()
        )
        if prefs is None:
            db.add(
                models.UserPreference(
                    user_id=founder.id,
                    document={"studio": {}, "assistant": {}, "notifications": {}},
                )
            )

        db.commit()
    finally:
        db.close()

    print(f"plans ensured: {', '.join(sorted(plans))}")
    if billing_ready:
        print(
            "billing catalogue: "
            f"created={catalogue_report['plans_created'] + catalogue_report['packages_created']} "
            f"updated={len(catalogue_report['plans_updated']) + len(catalogue_report['packages_updated'])}"
        )
    else:
        print(
            "billing catalogue: skipped (pre-0013 schema; "
            "re-run this seed after upgrading to head)"
        )
    print(f"founder: {email} ({'created' if created else 'already existed'})")
    if password_changed:
        print(f"initial password written to: {password_file} (mode 0600)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
