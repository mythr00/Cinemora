"""Research Studio (founder priority #6; gap-audit Phase D v1).

The audit's central finding (doc 01 §1): Cinemora has a substantial
research *engine* and no research *studio* — the Case Bible,
kb_client corroboration and script_facts exist only as internal
pipeline stages, driven by a finished script. This module is the
workspace OVER that engine, never a parallel store:

- PERSISTENCE is one project artefact, ``research_studio.json`` in
  the project directory — the same artefact pattern as
  plan_decisions.json (audit §1.5: "extend projects artefacts, do
  not invent a parallel store"). It holds research sessions, the
  persisted source library, citations, entity corrections, entity
  KB checks, user timeline events, fact-check runs and summaries.
- SESSIONS run the existing machinery only: services.research
  (query angles + Serper via search_provider) and kb_client for
  the topic verdict. No second search stack.
- The Case Bible surface READS case_bible.json exactly as recorded
  (entities, timeline, script_facts) and never rewrites it except
  through the fact-check operation, which runs the pipeline's own
  corroboration (script_facts.corroborate_facts) and writes the
  bible back to the very path it was read from.
- ENTITY CORRECTIONS are user artefacts in the studio store. The
  bible view applies them as an overlay (the recorded value is
  always shown beside the corrected one), and
  jobs.build_production_scenes applies them to the analysed bible
  before the Case Bible / plan documents are written — so a
  correction demonstrably changes the next plan and production.
- CREDIBILITY is a tier, never a score (audit §1.4): derived only
  from recorded signals — the provider that returned the source
  and its domain class — under the published rubric in
  ``credibility_tier``.
- SUMMARIES are generated by llm_client over KEPT sources only,
  stored with the exact source ids they compress, and refuse to
  run when there is nothing kept to cite (audit §1.11).
- CONTRADICTIONS are surfaced only where the engine records them:
  a KB verdict whose type disagrees with the bible's recorded
  entity type is presented with BOTH sides verbatim, never
  adjudicated (audit §1.10's presentation rule; full two-source
  contradiction detection is Phase D sub-phase 2).
- GAPS are deterministic derivations over recorded data
  (uncorroborated facts, unchecked facts, low-confidence entity
  types, entities no kept source mentions) — labelled as such.

Every failure is data or a ResearchError with the v1 shape; this
module never fabricates a source, a verdict or a summary.
"""

from __future__ import annotations

import re
import uuid
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

from services import kb_client, llm_client, media_paths, research
from services import script_facts
from services.atomic_write import write_json_atomic

STORE_FILENAME = "research_studio.json"
BIBLE_FILENAME = "case_bible.json"

# The bible's entity-type vocabulary (story_understanding cleans
# types into this set; corrections must speak the same language).
ENTITY_TYPES = ("person", "place", "organization", "event", "object", "other")

SOURCE_STATES = ("candidate", "kept", "discarded")


class ResearchError(Exception):
    """A domain error with an HTTP status + stable machine code
    (the API layer maps it onto the v1 error shape)."""

    def __init__(self, status_code: int, code: str, message: str,
                 details=None):
        super().__init__(message)
        self.status_code = status_code
        self.code = code
        self.message = message
        self.details = details


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _new_id(prefix: str) -> str:
    return f"{prefix}_{uuid.uuid4().hex[:16]}"


def _project_dir(project_id) -> Path:
    return media_paths.project_dir(project_id)


# ---------------------------------------------------------------------
# Store (the research_studio.json project artefact)
# ---------------------------------------------------------------------


def _empty_store() -> dict:
    return {
        "version": 1,
        "sessions": [],
        "sources": [],
        "citations": [],
        "entity_corrections": [],
        "entity_checks": [],
        "timeline_events": [],
        "fact_check_runs": [],
        "summaries": [],
    }


def load_store(project_id) -> dict:
    """The studio store for a project; an empty store when the
    project has never used the Studio (absence is not an error —
    research-before-script starts from exactly this state)."""
    path = _project_dir(project_id) / STORE_FILENAME
    try:
        import json

        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return _empty_store()
    if not isinstance(data, dict):
        return _empty_store()
    store = _empty_store()
    for key in store:
        if isinstance(data.get(key), list):
            store[key] = data[key]
    store["version"] = data.get("version") or 1
    return store


def save_store(project_id, store: dict) -> dict:
    project_dir = _project_dir(project_id)
    project_dir.mkdir(parents=True, exist_ok=True)
    write_json_atomic(project_dir / STORE_FILENAME, store)
    return store


# ---------------------------------------------------------------------
# Credibility tiers (audit §1.4 — tiers from recorded signals only)
# ---------------------------------------------------------------------

# Established-press domains for the tier rubric. This is a fixed,
# published classification list (a rubric, not a judgement call per
# source): a domain not on it is simply "web", never penalised
# beyond the honest label.
_PRESS_DOMAINS = {
    "apnews.com", "bbc.co.uk", "bbc.com", "bloomberg.com",
    "economist.com", "ft.com", "latimes.com", "npr.org",
    "nytimes.com", "reuters.com", "theguardian.com",
    "washingtonpost.com", "wsj.com",
}

_KNOWLEDGE_HOSTS = {
    "en.wikipedia.org", "www.wikidata.org", "wikidata.org",
    "commons.wikimedia.org",
}


def credibility_tier(url: str | None, provider: str | None) -> str:
    """The credibility tier for one source, derived ONLY from its
    provider and domain class:

    - ``primary_source``: an official-records domain (.gov / .mil)
      or the Internet Archive (provider archive_org / archive.org)
      — the source is the record itself or its archival host.
    - ``institutional``: a knowledge-base host (Wikipedia /
      Wikidata / Wikimedia Commons) or an educational domain
      (.edu / .ac.*) — curated institutional reference.
    - ``established_press``: a domain on the published press list.
    - ``web``: any other web source — no tier judgement recorded.
    - ``unknown``: no URL to classify.
    """
    if not url:
        return "unknown"
    host = (urlparse(url).hostname or "").lower()
    if not host:
        return "unknown"
    if provider == "archive_org" or host == "archive.org" or (
        host.endswith(".gov") or host.endswith(".mil")
    ):
        return "primary_source"
    if (
        host in _KNOWLEDGE_HOSTS
        or provider in ("wikidata", "wikipedia", "wikimedia_commons")
        or host.endswith(".edu")
        or ".ac." in host
    ):
        return "institutional"
    bare = host[4:] if host.startswith("www.") else host
    if bare in _PRESS_DOMAINS or host in _PRESS_DOMAINS:
        return "established_press"
    return "web"


def _domain_of(url: str | None) -> str | None:
    if not url:
        return None
    return (urlparse(url).hostname or "").lower() or None


# ---------------------------------------------------------------------
# Research sessions (audit §1.1 / §1.2)
# ---------------------------------------------------------------------


def run_session(project_id, topic: str) -> dict:
    """Run one topic research session over the existing machinery
    (services.research query angles + Serper, kb_client for the
    topic verdict) and persist the session + its sources into the
    project library.

    Sources are deduplicated by URL across the whole library: a
    result the project already holds is referenced, not copied.
    Search failures are recorded per query exactly as the engine
    reports them; when EVERY query failed, the session is refused
    with 503 search_unavailable (the assistant's honest contract)
    and nothing is persisted.
    """
    topic = str(topic or "").strip()
    if not topic:
        raise ResearchError(422, "topic_required", "A research topic is required.")
    if len(topic) > 500:
        raise ResearchError(422, "topic_too_long", "Topic is limited to 500 characters.")

    scene = {"scene_number": 0, "narration": topic, "visual_description": topic}
    result = research.research_scene(scene)

    raw_sources = result.get("sources") or []
    errors = [s for s in raw_sources if s.get("source") == "error"]
    real = [s for s in raw_sources if s.get("source") != "error" and s.get("url")]
    if not real and errors:
        raise ResearchError(
            503,
            "search_unavailable",
            "Web search is unavailable: "
            + "; ".join(
                str(e.get("snippet") or "search failed") for e in errors[:2]
            ),
        )

    # The topic's KB verdict, recorded verbatim (failures are data:
    # lookup_entity never raises by contract, but stay fail-soft).
    kb_verdict = None
    try:
        verdict = kb_client.lookup_entity(topic, budget=kb_client.KBBudget())
        kb_verdict = {
            "status": verdict.get("status"),
            "type": verdict.get("type"),
            "confidence": verdict.get("confidence"),
            "type_source": verdict.get("type_source"),
            "description": verdict.get("description"),
            "evidence": verdict.get("evidence"),
        }
    except Exception as error:  # recorded, never silent
        kb_verdict = {"status": "lookup_failed", "error": f"{type(error).__name__}: {error}"}

    store = load_store(project_id)
    session_id = _new_id("sess")
    by_url = {}
    for existing in store["sources"]:
        if existing.get("url"):
            by_url.setdefault(existing["url"], existing)

    source_ids = []
    new_count = 0
    for item in real:
        url = item["url"]
        existing = by_url.get(url)
        if existing is not None:
            if session_id not in existing.setdefault("session_ids", []):
                existing["session_ids"].append(session_id)
            if existing["id"] not in source_ids:
                source_ids.append(existing["id"])
            continue
        record = {
            "id": _new_id("src"),
            "session_ids": [session_id],
            "title": item.get("title") or "",
            "url": url,
            "snippet": item.get("snippet") or "",
            "provider": item.get("source") or "google_serper",
            "research_type": item.get("research_type"),
            "query": item.get("query"),
            "domain": _domain_of(url),
            "tier": credibility_tier(url, item.get("source")),
            "state": "candidate",
            "created_at": _now_iso(),
        }
        store["sources"].append(record)
        by_url[url] = record
        source_ids.append(record["id"])
        new_count += 1

    session = {
        "id": session_id,
        "topic": topic,
        "created_at": _now_iso(),
        "queries": result.get("queries") or [],
        "source_ids": source_ids,
        "kb_verdict": kb_verdict,
        "record": {
            "results": len(real),
            "new_sources": new_count,
            "reused_sources": len(source_ids) - new_count,
            "query_errors": [
                {"query": e.get("query"), "error": e.get("snippet")}
                for e in errors
            ],
        },
    }
    store["sessions"].append(session)
    save_store(project_id, store)
    return session_view(store, session)


def session_view(store: dict, session: dict) -> dict:
    by_id = {s["id"]: s for s in store["sources"]}
    sources = [by_id[sid] for sid in session.get("source_ids") or [] if sid in by_id]
    return {
        **session,
        "sources": sources,
        "kept_count": sum(1 for s in sources if s.get("state") == "kept"),
    }


def list_sessions(project_id) -> list:
    store = load_store(project_id)
    return [session_view(store, s) for s in store["sessions"]]


def get_session(project_id, session_id: str) -> dict:
    store = load_store(project_id)
    for session in store["sessions"]:
        if session["id"] == session_id:
            return session_view(store, session)
    raise ResearchError(404, "session_not_found", f"No research session {session_id}.")


# ---------------------------------------------------------------------
# Source library (audit §1.2 — persisted lists, keep semantics)
# ---------------------------------------------------------------------


def list_sources(project_id, *, state: str | None = None, query: str | None = None) -> dict:
    store = load_store(project_id)
    sources = list(store["sources"])
    if state:
        if state not in SOURCE_STATES:
            raise ResearchError(
                422, "invalid_state",
                f"Source state must be one of {', '.join(SOURCE_STATES)}.",
            )
        sources = [s for s in sources if s.get("state") == state]
    if query:
        needle = str(query).lower()
        sources = [
            s for s in sources
            if needle in (s.get("title") or "").lower()
            or needle in (s.get("snippet") or "").lower()
            or needle in (s.get("url") or "").lower()
        ]
    counts = {
        state_name: sum(1 for s in store["sources"] if s.get("state") == state_name)
        for state_name in SOURCE_STATES
    }
    tiers = {}
    for source in store["sources"]:
        tiers[source.get("tier") or "unknown"] = tiers.get(source.get("tier") or "unknown", 0) + 1
    return {"sources": sources, "counts": counts, "tiers": tiers, "total": len(store["sources"])}


def set_source_state(project_id, source_id: str, state: str) -> dict:
    if state not in SOURCE_STATES:
        raise ResearchError(
            422, "invalid_state",
            f"Source state must be one of {', '.join(SOURCE_STATES)}.",
        )
    store = load_store(project_id)
    for source in store["sources"]:
        if source["id"] == source_id:
            source["state"] = state
            source["state_at"] = _now_iso()
            save_store(project_id, store)
            return source
    raise ResearchError(404, "source_not_found", f"No research source {source_id}.")


def add_external_source(project_id, title: str, url: str) -> dict:
    """A user-supplied source (citation target / manual addition).
    Recorded as user_supplied with its tier derived by the same
    rubric; never presented as a search result."""
    title = str(title or "").strip()
    url = str(url or "").strip()
    if not url or not urlparse(url).hostname:
        raise ResearchError(422, "invalid_url", "A source needs a valid URL.")
    if not title:
        title = url
    store = load_store(project_id)
    for existing in store["sources"]:
        if existing.get("url") == url:
            return existing
    record = {
        "id": _new_id("src"),
        "session_ids": [],
        "title": title,
        "url": url,
        "snippet": "",
        "provider": "user_supplied",
        "research_type": None,
        "query": None,
        "domain": _domain_of(url),
        "tier": credibility_tier(url, "user_supplied"),
        "state": "kept",
        "created_at": _now_iso(),
    }
    store["sources"].append(record)
    save_store(project_id, store)
    return record


