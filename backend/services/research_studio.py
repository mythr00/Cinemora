def _claim_label(bible: dict | None, claim: dict) -> str:
    kind = claim.get("kind")
    if kind == "fact":
        fact_id = claim.get("fact_id")
        for fact in _fact_list(bible):
            if fact.get("fact_id") == fact_id:
                if fact.get("kind") == "dated_event":
                    return f"{fact.get('when')}: {fact.get('what')}"
                return str(fact.get("display") or fact.get("what") or fact_id)
        raise ResearchError(
            422, "fact_not_found",
            f"The recorded Case Bible has no fact {fact_id} to cite.",
        )
    if kind == "timeline_event":
        fact_id = claim.get("fact_id")
        if fact_id:
            for entry in (bible or {}).get("timeline") or []:
                if isinstance(entry, dict) and entry.get("fact_id") == fact_id:
                    return f"{entry.get('when')}: {entry.get('what')}"
            raise ResearchError(
                422, "event_not_found",
                f"The recorded Case Bible has no timeline event for fact {fact_id}.",
            )
        label = str(claim.get("label") or "").strip()
        if label:
            return label
        raise ResearchError(
            422, "claim_label_required",
            "A timeline-event citation needs a fact_id or a label.",
        )
    if kind == "statement":
        label = str(claim.get("label") or "").strip()
        if not label:
            raise ResearchError(
                422, "claim_label_required",
                "A statement citation needs the statement text as its label.",
            )
        return label
    raise ResearchError(
        422, "invalid_claim_kind",
        "Claim kind must be fact, timeline_event or statement.",
    )


def add_citation(project_id, claim: dict, *, source_id: str | None = None,
                 external: dict | None = None, note: str | None = None) -> dict:
    if not isinstance(claim, dict) or not claim.get("kind"):
        raise ResearchError(422, "claim_required", "A citation needs a claim.")
    bible, _path = _read_bible(project_id)
    label = _claim_label(bible, claim)
    store = load_store(project_id)
    source = None
    if source_id:
        source = next((s for s in store["sources"] if s["id"] == source_id), None)
        if source is None:
            raise ResearchError(
                404, "source_not_found", f"No research source {source_id}."
            )
    elif external:
        source = add_external_source(
            project_id, external.get("title") or "", external.get("url") or ""
        )
        store = load_store(project_id)
        source = next(s for s in store["sources"] if s["id"] == source["id"])
    else:
        raise ResearchError(
            422, "source_required",
            "A citation needs a library source_id or an external {title, url}.",
        )
    citation = {
        "id": _new_id("cit"),
        "claim": {
            "kind": claim.get("kind"),
            "fact_id": claim.get("fact_id"),
            "sentence_number": claim.get("sentence_number"),
            "label": label,
        },
        "source_id": source["id"],
        "note": (str(note).strip() or None) if note else None,
        "created_at": _now_iso(),
    }
    store["citations"].append(citation)
    save_store(project_id, store)
    return citation_view(store, citation)


def citation_view(store: dict, citation: dict) -> dict:
    source = next(
        (s for s in store["sources"] if s["id"] == citation["source_id"]), None
    )
    return {**citation, "source": source}


def list_citations(project_id) -> list:
    store = load_store(project_id)
    return [citation_view(store, c) for c in store["citations"]]


def delete_citation(project_id, citation_id: str) -> None:
    store = load_store(project_id)
    kept = [c for c in store["citations"] if c["id"] != citation_id]
    if len(kept) == len(store["citations"]):
        raise ResearchError(
            404, "citation_not_found", f"No citation {citation_id}."
        )
    store["citations"] = kept
    save_store(project_id, store)


def bibliography(project_id) -> dict:
    """The project's bibliography: one entry per citation (claim
    -> source), in citation order, plus a plain-text rendering.
    Every field comes from the recorded source — nothing is
    formatted into existence."""
    store = load_store(project_id)
    entries = []
    lines = []
    for index, citation in enumerate(store["citations"], start=1):
        view = citation_view(store, citation)
        source = view.get("source") or {}
        entry = {
            "number": index,
            "citation_id": citation["id"],
            "claim_label": citation["claim"]["label"],
            "claim_kind": citation["claim"]["kind"],
            "source_title": source.get("title"),
            "source_url": source.get("url"),
            "provider": source.get("provider"),
            "tier": source.get("tier"),
        }
        entries.append(entry)
        lines.append(
            f"[{index}] {entry['claim_label']} — {entry['source_title'] or ''} "
            f"<{entry['source_url'] or ''}> (via {entry['provider'] or 'unknown'}, "
            f"tier: {entry['tier'] or 'unknown'})"
        )
    return {"entries": entries, "text": "\n".join(lines)}


