def _validate_event_sources(store: dict, source_ids) -> list:
    valid = {s["id"] for s in store["sources"]}
    cleaned = []
    for source_id in source_ids or []:
        if source_id not in valid:
            raise ResearchError(
                422, "source_not_found",
                f"Timeline events can only cite library sources; {source_id} is not one.",
            )
        if source_id not in cleaned:
            cleaned.append(source_id)
    return cleaned


def add_timeline_event(project_id, when: str, what: str, source_ids=None) -> dict:
    when = str(when or "").strip()
    what = str(what or "").strip()
    if not when or not what:
        raise ResearchError(
            422, "event_incomplete", "A timeline event needs both a date (when) and a description (what)."
        )
    store = load_store(project_id)
    event = {
        "id": _new_id("evt"),
        "when": when,
        "what": what,
        "source_ids": _validate_event_sources(store, source_ids),
        "created_at": _now_iso(),
        "updated_at": None,
    }
    store["timeline_events"].append(event)
    save_store(project_id, store)
    return event


def update_timeline_event(project_id, event_id: str, *, when=None, what=None,
                          source_ids=None) -> dict:
    store = load_store(project_id)
    for event in store["timeline_events"]:
        if event["id"] == event_id:
            if when is not None:
                if not str(when).strip():
                    raise ResearchError(422, "event_incomplete", "A timeline event needs a date (when).")
                event["when"] = str(when).strip()
            if what is not None:
                if not str(what).strip():
                    raise ResearchError(422, "event_incomplete", "A timeline event needs a description (what).")
                event["what"] = str(what).strip()
            if source_ids is not None:
                event["source_ids"] = _validate_event_sources(store, source_ids)
            event["updated_at"] = _now_iso()
            save_store(project_id, store)
            return event
    raise ResearchError(404, "event_not_found", f"No studio timeline event {event_id}.")


def delete_timeline_event(project_id, event_id: str) -> None:
    store = load_store(project_id)
    kept = [e for e in store["timeline_events"] if e["id"] != event_id]
    if len(kept) == len(store["timeline_events"]):
        raise ResearchError(404, "event_not_found", f"No studio timeline event {event_id}.")
    store["timeline_events"] = kept
    save_store(project_id, store)


