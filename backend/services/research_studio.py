# Entity KB checks (audit §1.10 — recorded disagreement, presented)
# ---------------------------------------------------------------------


def latest_entity_checks(store: dict) -> dict:
    latest: dict = {}
    for check in store["entity_checks"]:
        latest[check["entity_id"]] = check
    return latest


def check_entity(project_id, entity_id: str) -> dict:
    """Look one bible entity up in the knowledge base and record
    the verdict beside the bible's recorded type. A disagreement
    is stored as a conflict with BOTH sides verbatim — the Studio
    presents it; it never adjudicates or rewrites the bible."""
    bible, _path = _read_bible(project_id)
    if bible is None:
        raise ResearchError(
            404, "bible_not_found",
            "No Case Bible is recorded for this project yet.",
        )
    entity = None
    for candidate in bible.get("entities") or []:
        if isinstance(candidate, dict) and candidate.get("id") == entity_id:
            entity = candidate
            break
    if entity is None:
        raise ResearchError(404, "entity_not_found", f"No bible entity {entity_id}.")
    name = entity.get("canonical") or entity_id
    verdict = kb_client.lookup_entity(name, budget=kb_client.KBBudget())
    kb_type = verdict.get("type")
    bible_type = entity.get("type")
    conflict = bool(
        kb_type and bible_type and kb_type != bible_type
        and verdict.get("evidence") == "verified"
    )
    check = {
        "id": _new_id("chk"),
        "entity_id": entity_id,
        "canonical": name,
        "bible_type": bible_type,
        "kb": {
            "status": verdict.get("status"),
            "type": kb_type,
            "confidence": verdict.get("confidence"),
            "type_source": verdict.get("type_source"),
            "description": verdict.get("description"),
            "evidence": verdict.get("evidence"),
        },
        "conflict": conflict,
        "created_at": _now_iso(),
    }
    store = load_store(project_id)
    store["entity_checks"].append(check)
    save_store(project_id, store)
    return check


# ---------------------------------------------------------------------
# Entity corrections (audit §1.7 — stored as project artefacts,
# fed to planning by jobs.build_production_scenes)
# ---------------------------------------------------------------------


def add_correction(project_id, entity_id: str, field: str, value: str) -> dict:
    if field not in ("type", "canonical"):
        raise ResearchError(
            422, "invalid_field",
            "Only an entity's type or canonical name can be corrected.",
        )
    value = str(value or "").strip()
    if field == "type" and value not in ENTITY_TYPES:
        raise ResearchError(
            422, "invalid_type",
            f"Entity type must be one of {', '.join(ENTITY_TYPES)}.",
        )
    if field == "canonical" and not value:
        raise ResearchError(422, "value_required", "A corrected name cannot be empty.")
    bible, _path = _read_bible(project_id)
    if bible is None:
        raise ResearchError(
            404, "bible_not_found",
            "No Case Bible is recorded for this project yet, so "
            "there is no entity to correct.",
        )
    entity = None
    for candidate in bible.get("entities") or []:
        if isinstance(candidate, dict) and candidate.get("id") == entity_id:
            entity = candidate
            break
    if entity is None:
        raise ResearchError(404, "entity_not_found", f"No bible entity {entity_id}.")
    original = entity.get("type") if field == "type" else entity.get("canonical")
    if value == original:
        raise ResearchError(
            422, "no_change",
            "The corrected value is identical to the recorded value.",
        )
    store = load_store(project_id)
    # One active correction per (entity, field): a re-correction
    # replaces the previous one, keeping its first-recorded time.
    existing = next(
        (
            c for c in store["entity_corrections"]
            if c["entity_id"] == entity_id and c["field"] == field
        ),
        None,
    )
    if existing is not None:
        existing["corrected"] = value
        existing["updated_at"] = _now_iso()
        save_store(project_id, store)
        return existing
    correction = {
        "id": _new_id("cor"),
        "entity_id": entity_id,
        "canonical": entity.get("canonical"),
        "field": field,
        "original": original,
        "corrected": value,
        "created_at": _now_iso(),
        "updated_at": None,
        "applied_at": None,
        "applications": 0,
    }
    store["entity_corrections"].append(correction)
    save_store(project_id, store)
    return correction


def delete_correction(project_id, correction_id: str) -> None:
    store = load_store(project_id)
    kept = [c for c in store["entity_corrections"] if c["id"] != correction_id]
    if len(kept) == len(store["entity_corrections"]):
        raise ResearchError(
            404, "correction_not_found", f"No entity correction {correction_id}."
        )
    store["entity_corrections"] = kept
    save_store(project_id, store)


def apply_entity_corrections(project_id, bible: dict) -> list:
    """Apply the project's stored corrections to an analysed bible
    IN PLACE (jobs.build_production_scenes calls this before the
    Case Bible and plan documents are written, so corrections feed
    planning and production). Returns the applied correction
    records. The bible entity keeps a `user_correction` stamp
    naming the recorded original — the correction is never silent.
    Corrections whose entity no longer exists in the bible are
    skipped and reported as such in the returned list."""
    if not isinstance(bible, dict):
        return []
    store = load_store(project_id)
    if not store["entity_corrections"]:
        return []
    by_id = {
        e.get("id"): e for e in bible.get("entities") or [] if isinstance(e, dict)
    }
    applied = []
    changed = False
    for correction in store["entity_corrections"]:
        entity = by_id.get(correction["entity_id"])
        if entity is None:
            applied.append({**correction, "applied": False, "reason": "entity_absent"})
            continue
        if correction["field"] == "type":
            entity["type"] = correction["corrected"]
        else:
            entity["canonical"] = correction["corrected"]
        stamps = entity.setdefault("user_corrections", [])
        stamps.append({
            "field": correction["field"],
            "original": correction["original"],
            "corrected": correction["corrected"],
            "correction_id": correction["id"],
        })
        correction["applied_at"] = _now_iso()
        correction["applications"] = int(correction.get("applications") or 0) + 1
        changed = True
        applied.append({**correction, "applied": True})
    if changed:
        # A corrected canonical name may rename the primary subject
        # reference only via its id (ids are stable), and the alias
        # index is derived at bible-build time — planning consumers
        # read entities/by_id, which key on ids, so no rebuild is
        # needed here; the by_id map values are the same dicts.
        by_id_map = bible.get("by_id")
        if isinstance(by_id_map, dict):
            for entity_id, entity in by_id.items():
                if entity_id in by_id_map:
                    by_id_map[entity_id] = entity
        save_store(project_id, store)
    return applied


