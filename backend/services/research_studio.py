def _read_bible(project_id) -> tuple[dict | None, Path]:
    project_dir = _project_dir(project_id)
    path = media_paths.resolve_artefact(project_dir, BIBLE_FILENAME)
    try:
        import json

        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None, path
    return (data if isinstance(data, dict) else None), path


def _fact_list(bible: dict | None) -> list:
    """The bible's script facts as a list, across both recorded
    shapes: the Phase 2.3 table dict {facts, record} and the bare
    list older readers assumed."""
    if not isinstance(bible, dict):
        return []
    table = bible.get("script_facts")
    if isinstance(table, dict):
        facts = table.get("facts")
        return facts if isinstance(facts, list) else []
    if isinstance(table, list):
        return table
    return []


def _fact_record(bible: dict | None) -> dict | None:
    if isinstance(bible, dict) and isinstance(bible.get("script_facts"), dict):
        record = bible["script_facts"].get("record")
        return record if isinstance(record, dict) else None
    return None


def corrections_by_entity(store: dict) -> dict:
    """entity_id -> {field: correction} for the ACTIVE corrections
    (the store only holds active ones; deletion removes)."""
    overlay: dict = {}
    for correction in store["entity_corrections"]:
        overlay.setdefault(correction["entity_id"], {})[correction["field"]] = correction
    return overlay


def apply_corrections_to_entities(entities: list, store: dict) -> list:
    """Project bible entities with the correction overlay applied:
    every entity keeps its recorded values and gains `effective_*`
    fields plus the correction records, so the recorded truth and
    the user's correction are both visible, never merged silently."""
    overlay = corrections_by_entity(store)
    projected = []
    for entity in entities or []:
        if not isinstance(entity, dict):
            continue
        view = dict(entity)
        applied = overlay.get(entity.get("id")) or {}
        view["effective_type"] = (
            applied["type"]["corrected"] if "type" in applied else entity.get("type")
        )
        view["effective_canonical"] = (
            applied["canonical"]["corrected"]
            if "canonical" in applied
            else entity.get("canonical")
        )
        view["corrections"] = [applied[k] for k in sorted(applied)]
        projected.append(view)
    return projected


def bible_view(project_id) -> dict:
    """The recorded Case Bible as a research document: entities
    (with corrections overlaid), the merged timeline (bible events
    + the user's own studio events, each labelled by origin), and
    the script-fact table with its basis stamps."""
    bible, _path = _read_bible(project_id)
    store = load_store(project_id)
    if bible is None:
        return {
            "recorded": False,
            "note": (
                "No Case Bible is recorded for this project yet; "
                "story analysis during plan generation or a "
                "production run produces it. Research sessions, "
                "sources and citations work before it exists."
            ),
            "entities": [],
            "timeline": _studio_timeline(store, []),
            "facts": [],
            "fact_record": None,
        }
    entities = apply_corrections_to_entities(bible.get("entities") or [], store)
    bible_events = []
    for entry in bible.get("timeline") or []:
        if not isinstance(entry, dict):
            continue
        bible_events.append({
            "origin": "case_bible",
            "when": entry.get("when"),
            "what": entry.get("what"),
            "support": entry.get("support"),
            "fact_basis": entry.get("fact_basis"),
            "fact_id": entry.get("fact_id"),
            "sentence_number": entry.get("sentence_number"),
        })
    checks = latest_entity_checks(store)
    for entity in entities:
        check = checks.get(entity.get("id"))
        entity["kb_check"] = check
    return {
        "recorded": True,
        "title": bible.get("title"),
        "story_type": bible.get("story_type"),
        "story_era": bible.get("story_era") or bible.get("time_period"),
        "mode": bible.get("mode"),
        "primary_subject_id": bible.get("primary_subject_id"),
        "entities": entities,
        "timeline": _studio_timeline(store, bible_events),
        "facts": _fact_list(bible),
        "fact_record": _fact_record(bible),
    }


def _studio_timeline(store: dict, bible_events: list) -> list:
    events = list(bible_events)
    for event in store["timeline_events"]:
        events.append({
            "origin": "studio",
            "id": event["id"],
            "when": event.get("when"),
            "what": event.get("what"),
            "support": "user_added",
            "fact_basis": None,
            "fact_id": None,
            "sentence_number": None,
            "source_ids": event.get("source_ids") or [],
            "created_at": event.get("created_at"),
        })
    return events


# ---------------------------------------------------------------------
# Fact check (audit §1.3 — the pipeline's own corroboration, on demand)
# ---------------------------------------------------------------------


def run_fact_check(project_id) -> dict:
    """Re-run KB corroboration over the bible's recorded fact
    table (script_facts.corroborate_facts, the exact function the
    production flow calls), refresh the timeline bases, and write
    the bible back to the path it was read from. The run record is
    kept in the studio store."""
    bible, path = _read_bible(project_id)
    if bible is None:
        raise ResearchError(
            404, "bible_not_found",
            "No Case Bible is recorded for this project yet, so "
            "there are no facts to check.",
        )
    facts = _fact_list(bible)
    if not facts:
        raise ResearchError(
            422, "no_facts",
            "The recorded Case Bible carries no script facts to check.",
        )
    record = script_facts.corroborate_facts(facts)
    script_facts.apply_fact_bases_to_timeline(bible, facts)
    if isinstance(bible.get("script_facts"), dict):
        bible["script_facts"]["facts"] = facts
    else:
        bible["script_facts"] = facts
    write_json_atomic(path, bible)

    store = load_store(project_id)
    run = {"id": _new_id("fc"), "created_at": _now_iso(), "record": record}
    store["fact_check_runs"].append(run)
    save_store(project_id, store)
    return {
        "run": run,
        "facts": facts,
        "bases": {
            basis: sum(1 for f in facts if f.get("basis") == basis)
            for basis in (script_facts.BASIS_SCRIPT, script_facts.BASIS_RESEARCH)
        },
    }


