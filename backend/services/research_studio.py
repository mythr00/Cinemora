def compute_gaps(project_id, bible: dict | None, store: dict) -> dict:
    """Coverage gaps derived ONLY from recorded data, each labelled
    with what it was derived from. Nothing here is an opinion: a
    fact is 'unverified' because its recorded basis is script_claim,
    an entity is 'without kept sources' because no kept source's
    recorded title/snippet mentions its name."""
    facts = _fact_list(bible)
    unverified = [f for f in facts if f.get("basis") == script_facts.BASIS_SCRIPT]
    unchecked = [
        f for f in facts
        if f.get("kind") == "dated_event" and "kb_check" not in f
    ]
    entities = (bible or {}).get("entities") or []
    low_confidence = [
        e.get("id") for e in entities
        if isinstance(e, dict) and e.get("type_low_confidence")
    ]
    checks = latest_entity_checks(store)
    conflicts = [c for c in checks.values() if c.get("conflict")]
    uncorroborated_events = [
        entry for entry in (bible or {}).get("timeline") or []
        if isinstance(entry, dict)
        and (entry.get("fact_basis") == script_facts.BASIS_SCRIPT
             or entry.get("support") == "script_asserted")
    ]
    kept = [s for s in store["sources"] if s.get("state") == "kept"]
    haystack = " ".join(
        f"{s.get('title') or ''} {s.get('snippet') or ''}".lower() for s in kept
    )
    without_sources = []
    for entity in entities:
        if not isinstance(entity, dict):
            continue
        names = [entity.get("canonical") or ""] + list(entity.get("aliases") or [])
        if not any(name and name.lower() in haystack for name in names):
            without_sources.append(entity.get("id"))
    return {
        "unverified_facts": {
            "count": len(unverified),
            "fact_ids": [f.get("fact_id") for f in unverified],
            "basis": "recorded fact basis is script_claim (asserted by the script, not corroborated)",
        },
        "unchecked_facts": {
            "count": len(unchecked),
            "fact_ids": [f.get("fact_id") for f in unchecked],
            "basis": "dated-event facts with no recorded kb_check",
        },
        "low_confidence_entity_types": {
            "count": len(low_confidence),
            "entity_ids": low_confidence,
            "basis": "the bible records type_low_confidence for these entities",
        },
        "entity_type_conflicts": {
            "count": len(conflicts),
            "checks": conflicts,
            "basis": "recorded KB verdict type disagrees with the bible's recorded type; both sides shown, never adjudicated",
        },
        "uncorroborated_timeline_events": {
            "count": len(uncorroborated_events),
            "basis": "bible timeline entries whose recorded basis is script-asserted",
        },
        "entities_without_kept_sources": {
            "count": len(without_sources),
            "entity_ids": without_sources,
            "basis": "no kept source's recorded title or snippet mentions the entity name or its aliases",
        },
    }


