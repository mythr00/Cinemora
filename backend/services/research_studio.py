_SUMMARY_SYSTEM = (
    "You are Cinemora's research summariser. Summarise ONLY the "
    "material provided below: the numbered sources and the recorded "
    "script facts. Cite sources inline as [n] using the numbers "
    "given. Never introduce a fact, name, date or figure that is "
    "not in the provided material; where the material is thin or "
    "silent on an aspect of the topic, say so plainly. Write a "
    "clear research brief of a few short paragraphs."
)


def generate_summary(project_id, session_id: str | None = None) -> dict:
    """Generate a research summary over the project's KEPT sources
    (one session's, or the whole library's), stored with the exact
    source ids it compresses. Refuses when nothing is kept — a
    summary must cite the sources it rests on. An LLM failure is a
    502, never a fabricated summary."""
    store = load_store(project_id)
    if session_id:
        session = next((s for s in store["sessions"] if s["id"] == session_id), None)
        if session is None:
            raise ResearchError(404, "session_not_found", f"No research session {session_id}.")
        wanted = set(session.get("source_ids") or [])
        sources = [
            s for s in store["sources"]
            if s["id"] in wanted and s.get("state") == "kept"
        ]
        topic = session["topic"]
    else:
        sources = [s for s in store["sources"] if s.get("state") == "kept"]
        topic = "the project's research"
    if not sources:
        raise ResearchError(
            422, "no_kept_sources",
            "No kept sources to summarise. Keep at least one source "
            "first — a summary must rest on cited sources.",
        )
    bible, _path = _read_bible(project_id)
    facts = _fact_list(bible)
    lines = [f"TOPIC: {topic}", "", "SOURCES:"]
    for index, source in enumerate(sources, start=1):
        lines.append(
            f"[{index}] {source.get('title') or ''} <{source.get('url') or ''}>"
        )
        if source.get("snippet"):
            lines.append(f"    {source['snippet']}")
    if facts:
        lines.append("")
        lines.append("RECORDED SCRIPT FACTS (basis-stamped):")
        for fact in facts[:40]:
            label = (
                fact.get("what") if fact.get("kind") == "dated_event"
                else fact.get("display")
            )
            lines.append(f"- {label} (basis: {fact.get('basis')})")
    try:
        text = llm_client.llm_text(_SUMMARY_SYSTEM, "\n".join(lines))
    except Exception as error:
        raise ResearchError(
            502, "summary_unavailable",
            f"Summary generation failed: {type(error).__name__}: {error}",
        ) from error
    if not text or not str(text).strip():
        raise ResearchError(
            502, "summary_unavailable",
            "Summary generation returned no text.",
        )
    summary = {
        "id": _new_id("sum"),
        "scope": "session" if session_id else "library",
        "session_id": session_id,
        "topic": topic,
        "text": str(text).strip(),
        "source_ids": [s["id"] for s in sources],
        "created_at": _now_iso(),
    }
    store["summaries"].append(summary)
    save_store(project_id, store)
    return summary_view(store, summary)


def summary_view(store: dict, summary: dict) -> dict:
    by_id = {s["id"]: s for s in store["sources"]}
    return {
        **summary,
        "sources": [by_id[sid] for sid in summary.get("source_ids") or [] if sid in by_id],
    }


def list_summaries(project_id) -> list:
    store = load_store(project_id)
    return [summary_view(store, s) for s in store["summaries"]]


